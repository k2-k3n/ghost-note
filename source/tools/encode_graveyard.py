"""Encode the Ghost Note scenery, sprite and startup animation."""
from itertools import groupby
from pathlib import Path
import struct
import zlib

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
W, H = 320, 172
GW, GH = 81, 78

def rgb565(pixel):
    r, g, b = pixel
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)

def array(name, values, kind):
    rows = [", ".join(map(str, values[i:i + 24])) for i in range(0, len(values), 24)]
    return f"static const {kind} {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"

def header(path, *arrays):
    (ROOT / "src" / path).write_text(
        "// Generated by tools/encode_weather.py.\n#pragma once\n#include <stdint.h>\n\n"
        + "\n".join(arrays)
    )

def indexed(image, colors, alpha=None):
    indexed_image = image.convert("RGB").quantize(colors=colors, dither=Image.Dither.NONE)
    table = indexed_image.getpalette()
    palette = [0] + [rgb565(table[i:i + 3]) for i in range(0, colors * 3, 3)]
    mask = alpha.tobytes() if alpha is not None else bytes([255]) * (image.width * image.height)
    return palette, [index + 1 if opacity >= 128 else 0
                     for index, opacity in zip(indexed_image.tobytes(), mask)]


yard = Image.open(ROOT / "assets/graveyard-v2.png").convert("RGB").resize((W, H), Image.Resampling.LANCZOS)
ghost = Image.open(ROOT / "assets/ghost-v2.png").convert("RGBA")
ghost = ghost.crop(ghost.getchannel("A").getbbox()).resize((GW, GH), Image.Resampling.LANCZOS)
alpha = ghost.getchannel("A")
assert alpha.getextrema() == (0, 255)
yard_palette, yard_pixels = indexed(yard, 176)
ghost_palette, ghost_pixels = indexed(ghost, 88, alpha)
# Foreground stone contour, in screen coordinates, for the retreat behind it.
stone = Image.new("1", (W, H))
ImageDraw.Draw(stone).polygon([(136, 154), (136, 116), (140, 110), (147, 103),
                              (155, 99), (165, 97), (174, 97), (184, 101),
                              (191, 109), (194, 117), (194, 154)], fill=1)
stone_top = [next((y for y in range(H) if stone.getpixel((x, y))), H) for x in range(W)]
header("graveyard.h", array("kYardPalette", yard_palette, "uint16_t"),
       array("kGhostPalette", ghost_palette, "uint16_t"),
       array("kYardPixels", yard_pixels, "uint8_t"), array("kClothPixels", ghost_pixels, "uint8_t"),
       array("kStoneTop", stone_top, "uint8_t"),
       "static const kit::Sprite kYard = {320, 172, 0, 0, kYardPixels};\n"
       "static const kit::Sprite kClothGhost = {81, 78, -40, 0, kClothPixels};\n")

mask = alpha.resize((50, 48), Image.Resampling.LANCZOS).point(lambda v: 255 if v >= 128 else 0)
frames = []
for i in range(19):
    frame = Image.new("RGB", (W, H))
    t = i / 18
    gain = min(i / 5, 1, (18 - i) / 6)
    y = round(99 - 54 * (t * t * (3 - 2 * t)))
    frame.paste(tuple(round(v * gain) for v in (83, 106, 158)), (140, y), mask)
    draw = ImageDraw.Draw(frame)
    for x in range(136, 195):
        edge = stone_top[x]
        if edge < H:
            draw.line((x, edge, x, 154), fill=(0, 0, 0))
    if gain:
        draw.arc((135, 97, 195, 129), 184, 356,
                 fill=tuple(round(v * gain) for v in (49, 58, 81)))
    frames.append(frame)

hold = 36
payload = bytearray()
for frame in frames:
    runs = [(sum(1 for _ in run), color) for color, run in groupby(map(rgb565, frame.get_flattened_data()))]
    payload.extend(struct.pack("<II", hold, len(runs)))
    for length, color in runs:
        payload.extend(struct.pack("<HH", length, color))
splash = struct.pack("<4s7I", b"RSP1", len(payload) + 32, zlib.crc32(payload),
                     hold * len(frames), W, H, len(frames), 0) + payload
assert len(splash) <= 24576
header("splash_data.h", array("kSplash", splash, "uint8_t"))
frames[0].save(ROOT.parent / "开机动画.gif", save_all=True, append_images=frames[1:],
               duration=hold, loop=0, disposal=2)
print(f"{len(frames)} frames, {len(splash)} bytes")
